export const GalleryController = {
  items: GALLERY_DATA,
  filteredItems: GALLERY_DATA,
  currentIndex: 0,
  activeCategory: "all",
  modalEl: null,
  touchStartX: 0,
  touchEndX: 0,

  init() {
    this.modalEl = document.getElementById('gallery-modal');
    this.bindCategoryFilters();
    this.bindGalleryCards();
    this.bindModalControls();
  },

  bindCategoryFilters() {
    const filterBtns = document.querySelectorAll('.gallery-filter-btn');
    const cards = document.querySelectorAll('.gallery-card');

    filterBtns.forEach(btn => {
      btn.addEventListener('click', () => {
        filterBtns.forEach(b => {
          b.classList.remove('is-active');
          b.setAttribute('aria-selected', 'false');
        });
        btn.classList.add('is-active');
        btn.setAttribute('aria-selected', 'true');

        const category = btn.getAttribute('data-gallery-filter');
        this.activeCategory = category;

        if (category === 'all') {
          this.filteredItems = this.items;
        } else {
          this.filteredItems = this.items.filter(item => item.category === category);
        }

        cards.forEach(card => {
          const cardCat = card.getAttribute('data-gallery-category');
          if (category === 'all' || cardCat === category) {
            card.style.display = 'flex';
          } else {
            card.style.display = 'none';
          }
        });
      });
    });
  },

  bindGalleryCards() {
    const cards = document.querySelectorAll('.gallery-card');
    cards.forEach(card => {
      const id = card.getAttribute('data-gallery-id');
      card.addEventListener('click', () => {
        const index = this.filteredItems.findIndex(i => i.id === id);
        if (index !== -1) {
          this.openLightbox(index);
        }
      });

      card.addEventListener('keydown', (e) => {
        if (e.key === 'Enter' || e.key === ' ') {
          e.preventDefault();
          card.click();
        }
      });
    });
  },

  bindModalControls() {
    if (!this.modalEl) return;

    const closeBtn = document.getElementById('gallery-modal-close');
    const nextBtn = document.getElementById('gallery-modal-next');
    const prevBtn = document.getElementById('gallery-modal-prev');

    if (closeBtn) closeBtn.addEventListener('click', () => this.closeLightbox());
    if (nextBtn) nextBtn.addEventListener('click', () => this.next());
    if (prevBtn) prevBtn.addEventListener('click', () => this.prev());

    // Click backdrop to close
    this.modalEl.addEventListener('click', (e) => {
      if (e.target === this.modalEl) {
        this.closeLightbox();
      }
    });

    // Keyboard navigation
    document.addEventListener('keydown', (e) => {
      if (!this.modalEl.classList.contains('is-open')) return;

      if (e.key === 'Escape') {
        this.closeLightbox();
      } else if (e.key === 'ArrowRight') {
        this.next();
      } else if (e.key === 'ArrowLeft') {
        this.prev();
      }
    });

    // Touch swipe gestures for mobile
    this.modalEl.addEventListener('touchstart', (e) => {
      this.touchStartX = e.changedTouches[0].screenX;
    }, { passive: true });

    this.modalEl.addEventListener('touchend', (e) => {
      this.touchEndX = e.changedTouches[0].screenX;
      this.handleSwipe();
    }, { passive: true });
  },

  handleSwipe() {
    const diff = this.touchStartX - this.touchEndX;
    const threshold = 45; // Min px swipe distance
    if (Math.abs(diff) > threshold) {
      if (diff > 0) {
        this.next(); // Swiped left -> next
      } else {
        this.prev(); // Swiped right -> prev
      }
    }
  },

  openLightbox(index) {
    if (!this.modalEl || !this.filteredItems[index]) return;
    this.currentIndex = index;
    this.renderLightboxContent();

    this.modalEl.classList.add('is-open');
    this.modalEl.setAttribute('aria-hidden', 'false');
    document.body.style.overflow = 'hidden';

    // Focus close button for accessibility
    const closeBtn = document.getElementById('gallery-modal-close');
    if (closeBtn) closeBtn.focus();
  },

  closeLightbox() {
    if (!this.modalEl) return;
    this.modalEl.classList.remove('is-open');
    this.modalEl.setAttribute('aria-hidden', 'true');
    document.body.style.overflow = '';
  },

  next() {
    if (this.filteredItems.length === 0) return;
    this.currentIndex = (this.currentIndex + 1) % this.filteredItems.length;
    this.renderLightboxContent();
  },

  prev() {
    if (this.filteredItems.length === 0) return;
    this.currentIndex = (this.currentIndex - 1 + this.filteredItems.length) % this.filteredItems.length;
    this.renderLightboxContent();
  },

  renderLightboxContent() {
    const item = this.filteredItems[this.currentIndex];
    if (!item) return;

    const imgEl = document.getElementById('modal-gallery-img');
    const titleEl = document.getElementById('modal-gallery-title');
    const hindiEl = document.getElementById('modal-gallery-hindi');
    const descEl = document.getElementById('modal-gallery-desc');
    const tradEl = document.getElementById('modal-gallery-tradition');
    const noteEl = document.getElementById('modal-gallery-sourcenote');
    const counterEl = document.getElementById('modal-gallery-counter');

    if (imgEl) {
      imgEl.src = item.image;
      imgEl.alt = item.title;
    }
    if (titleEl) titleEl.textContent = item.title;
    if (hindiEl) hindiEl.textContent = item.hindiTitle;
    if (descEl) descEl.textContent = item.desc;
    if (tradEl) tradEl.textContent = item.tradition;
    if (noteEl) noteEl.textContent = item.sourceNote;
    if (counterEl) {
      counterEl.textContent = `${this.currentIndex + 1} / ${this.filteredItems.length}`;
    }
  }
};
